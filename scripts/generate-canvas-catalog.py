#!/usr/bin/env python3
"""Generate the bundled Swift catalog and readable list from reviewed evidence.

No network calls. Update docs/canvas-directory/schools.json only after reviewing
first-party directory or university evidence and any cross-host redirects.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/canvas-directory/schools.json'
OUT = ROOT / 'LowHangingFruitKit/Sources/LowHangingFruitKit/Canvas/CanvasSchoolCatalogData.swift'

def literal(value):
    # ASCII escaping from JSON is not Swift unicode escaping. Keep UTF-8 text.
    return json.dumps(value, ensure_ascii=False)

def main():
    catalog = json.loads(SOURCE.read_text())
    rows = catalog['schools']
    assert len({r['id'] for r in rows}) == len(rows)
    assert len({r['host'] for r in rows}) == len(rows)
    lines = ['// Generated by scripts/generate-canvas-catalog.py. Edit the reviewed JSON source.',
             '// Address checks do not imply authenticated integration testing.',
             'import Foundation', '', 'extension CanvasSchoolCatalog {',
             '    static let entries: [Entry] = [']
    for row in rows:
        fields = [('id',row['id']),('name',row['name']),('host',row['host'])]
        if row.get('loginURL'): fields.append(('login',row['loginURL']))
        fields += [('aliases',';'.join(row['aliases'])),('hostAliases',';'.join(row['hostAliases']))]
        lines.append('        Entry('+', '.join(key+': '+literal(value) for key,value in fields)+'),')
    lines += ['    ]','}', '']
    OUT.write_text('\n'.join(lines))
    table = [f"# Bundled US Canvas catalog: {len(rows)} distinct sites", '',
             f"Address evidence checked {catalog['checkedOn']}. These are major US universities, university campuses and shared university systems, not a published top-200 ranking. Shared Canvas sites appear once and are searchable by campus names. All entries work in local school search without a directory request; actual sign-in requires internet.", '',
             'Each address has first-party Instructure directory evidence and an unauthenticated Canvas HTTP check. This does **not** mean authenticated Smooth sign-in, calendar discovery and sync have been tested at every school. See [limits and exclusions](LIMITATIONS.md).', '',
             '| University / shared Canvas site | Canvas origin | Search aliases |', '|---|---|---|']
    for r in rows:
        table.append(f"| {r['name']} | [{r['host']}](https://{r['host']}) | {', '.join(r['aliases'])} |")
    table += ['', 'The complete evidence, source directory IDs, login routes, host aliases and public HTTP-check results are in [schools.json](schools.json).', '']
    (SOURCE.parent/'SCHOOLS.md').write_text('\n'.join(table))
    print(f'Generated {len(rows)} schools in {OUT.name} and SCHOOLS.md')

if __name__ == '__main__':
    main()
