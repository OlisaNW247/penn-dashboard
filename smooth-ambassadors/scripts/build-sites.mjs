// Folds the ambassador system into the hosting platform's single-file tracker.
//
//   node scripts/build-sites.mjs <path-to-sites-repository>
//
// The platform runs `node --check worker/index.js`, `bash scripts/build.sh`, then
// imports dist/server/index.js, with no `npm install`. So the deployed Worker must
// stay ONE self-contained ES module with no imports. This script bundles
// sites/entry.js (the ambassador system, with its catalog and legacy helpers
// replaced by sites/host-*.js) into an IIFE and appends it to worker/index.js,
// plus two small edits to the existing fetch handler. Everything else, including
// the giant embedded-image line, is left byte for byte as it was: the file is
// treated as a string and never reformatted.
//
// It is idempotent: a second run rewrites only the generated section.
// Every anchor must occur exactly once or nothing is written.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { join, dirname, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = process.argv[2] && resolve(process.argv[2]);
if (!repo) {
  console.error("usage: node scripts/build-sites.mjs <path-to-sites-repository>");
  process.exit(2);
}
const target = join(repo, "worker/index.js");

const START =
  "// >>> smooth-ambassadors: generated by smooth-ambassadors/scripts/build-sites.mjs. Do not edit by hand; edit the source and rebuild.";
const END = "// <<< smooth-ambassadors";

const A_OLD = "  async fetch(request, env) {\n    const url = new URL(request.url);\n";
const A_NEW = `  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    // Ambassador system: the generated section at the end of this file. It answers only
    // /a/..., /r/..., /f/... and /api/leaderboard, and returns null for every other path
    // before touching the database, so the routes below behave exactly as before.
    const ambassadorResponse = await smoothAmbassadors.handle(request, env, ctx);
    if (ambassadorResponse) return ambassadorResponse;
`;
const B_ANCHOR = ".bind(counterKey(school, poster)).run();\n";
const B_INSERT = `      // Also log the scan with a timestamp so "last 14 days" numbers exist. The total above is
      // already saved; this runs after the redirect is sent and can never delay or fail it.
      ctx?.waitUntil?.(smoothAmbassadors.logScan(env, counterKey(school, poster)).catch(() => {}));
`;

const count = (text, needle) => text.split(needle).length - 1;
function fail(msg) {
  console.error("build-sites: " + msg + " (nothing written)");
  process.exit(1);
}

let text = readFileSync(target, "utf8");

// Drop any previous generated section; what is left is the host file plus A and B.
const startAt = text.indexOf(START);
if (startAt !== -1) {
  if (count(text, START) !== 1 || count(text, END) !== 1) fail("generated markers are not unique");
  text = text.slice(0, startAt);
}
if (!text.endsWith("\n")) text += "\n";

// Edit A.
if (count(text, A_NEW) === 1) {
  // already applied
} else if (count(text, A_OLD) === 1) {
  text = text.replace(A_OLD, () => A_NEW);
} else {
  fail(`edit A: anchor found ${count(text, A_OLD)} times, expected 1`);
}

// Edit B.
if (count(text, B_INSERT) === 1) {
  // already applied
} else if (count(text, B_ANCHOR) === 1) {
  text = text.replace(B_ANCHOR, () => B_ANCHOR + B_INSERT);
} else {
  fail(`edit B: anchor found ${count(text, B_ANCHOR)} times, expected 1`);
}
if (count(text, A_NEW) !== 1 || count(text, B_INSERT) !== 1) fail("edits A and B must each be present exactly once");
for (const needle of ["const appStore =", "const posters = new Map(", "const schools = new Map(", "function counterKey(", "async function initialize("]) {
  if (count(text, needle) !== 1) fail(`host file: "${needle}" found ${count(text, needle)} times, expected 1`);
}

// Bundle. The alias applies only to imports made from worker/, so sites/host-*.js
// can still import the real catalog for the helpers that do not depend on the lists.
const workerDir = join(root, "worker") + sep;
const alias = {
  name: "host-alias",
  setup(b) {
    b.onResolve({ filter: /^\.\/(catalog|legacy)\.js$/ }, (args) => {
      if (!args.importer.startsWith(workerDir)) return null;
      return { path: join(root, "sites", "host-" + args.path.slice(2)) };
    });
  },
};
const result = await build({
  entryPoints: [join(root, "sites/entry.js")],
  bundle: true,
  format: "iife",
  globalName: "smoothAmbassadors",
  platform: "browser",
  target: "es2022",
  minify: false,
  write: false,
  legalComments: "inline",
  loader: { ".sql": "text", ".woff2": "base64" },
  plugins: [alias],
  logLevel: "silent",
});
const bundle = result.outputFiles[0].text;

const host = `const SMOOTH_HOST = {
  appStore, posters, schools, counterKey, initialize,
  // Designs printed for UPenn only. Keep in step with the two ['jester', 'regista'] checks above.
  upennOnly: ['jester', 'regista'],
};
`;
text += START + "\n" + host + bundle + (bundle.endsWith("\n") ? "" : "\n") + END + "\n";

writeFileSync(target, text);
mkdirSync(join(repo, "migrations"), { recursive: true });
for (const file of ["0001_ambassadors.sql", "0002_poster_ideas.sql"]) {
  copyFileSync(join(root, "migrations", file), join(repo, "migrations", file));
}

// The repository's own account of the change. The platform build copies only
// worker/index.js and the hosting manifest, so these files never reach the Worker;
// they are for whoever opens the repository next.
copyFileSync(join(root, "sites/AMBASSADORS.md"), join(repo, "AMBASSADORS.md"));
const readmePath = join(repo, "README.md");
const README_NOTE = `
## Ambassador system

\`worker/index.js\` also serves the campus ambassador system that the Smooth iOS app signs in to: \`/a/{code}/...\` (private), \`/r/{ref}/...\` (the public share and sticker links), \`/f/{FOUNDER_TOKEN}/...\` and \`/api/leaderboard\`. It is the generated section at the end of the file, and it still needs no dependencies and no install. Routes, runtime variables, schema and the checks to run after a deploy are in \`AMBASSADORS.md\`.
`;
const readme = readFileSync(readmePath, "utf8");
if (!readme.includes("## Ambassador system")) {
  writeFileSync(readmePath, readme + (readme.endsWith("\n") ? "" : "\n") + README_NOTE);
}
console.log(`build-sites: wrote ${target} (${text.length} chars)`);
